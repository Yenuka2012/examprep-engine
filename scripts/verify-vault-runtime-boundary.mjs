/**
 * M2.8 dedicated review gate. Static dependency check for the experimental
 * encrypted examination runtime, not a substitute for independent CodeQL.
 * Fails closed if the encrypted runtime ever pulls legacy database/write
 * modules into its transitive source import graph.
 */
import {readFileSync,realpathSync,existsSync,statSync} from 'node:fs';
import {resolve,dirname,relative,sep} from 'node:path';

const root=realpathSync(process.cwd());
const entry=resolve(root,'src/vault/encryptedExamRuntime.ts');
const banned=new Set([
  'src/db.ts','src/catalog.ts','src/examPersistence.ts',
  'src/legacyWriteBarrier.ts','src/storageVersionGuard.ts',
  'src/vault/syntheticLegacy.ts'
]);
const visited=new Set();
const fail=msg=>{throw new Error('Encrypted-only runtime dependency boundary failed: '+msg);};
const extensions=['','.ts','.tsx','.js','.mjs','/index.ts','/index.tsx','/index.js'];
function resolveRelative(source,specifier){
  if(!specifier.startsWith('.'))return null;
  const candidate=resolve(dirname(source),specifier);
  for(const extension of extensions){
    const p=candidate+extension;
    if(!existsSync(p)||!statSync(p).isFile())continue;
    const path=realpathSync(p);
    if(path!==root&&!path.startsWith(root+sep))fail('unexpected import outside project');
    return path;
  }
  fail('unresolved relative import in '+relative(root,source));
}
function walk(file){
  const path=realpathSync(file);
  const name=relative(root,path).replaceAll('\\','/');
  if(banned.has(name))fail('legacy source module reached: '+name);
  if(!name.startsWith('src/'))fail('unexpected runtime module outside src');
  if(visited.has(name))return;
  visited.add(name);
  const source=readFileSync(path,'utf8');
  // This single validator file is generated by the separately hash-pinned
  // scripts/generate-validator.mjs. AJV standalone code may contain require()
  // inside emitted validator functions. Treat it as a terminal generated
  // artifact, but still reject any legacy/browser storage or network token.
  if(name==='src/generated/validate-bank.js'){
    if(/\b(?:indexedDB|localStorage|XMLHttpRequest)\b|examprep-v1|\bfetch\s*\(/.test(source)||
       /\brequire\s*\(\s*['"]\.\.?\//.test(source)){
      fail('generated schema validator references external storage or code');
    }
    return;
  }
  if(/\bimport\s*\(|\brequire\s*\(/.test(source)){
    fail('dynamic import/require is not reviewable in '+name);
  }
  // Explicit imports and re-exports, including multiline type imports.
  // Do not silently ignore unresolved relative imports.
  const specifiers=[
    ...[...source.matchAll(/^\s*(?:import|export)\s+(?:type\s+)?[\w*{},\s]+?\s+from\s*['"]([^'"]+)['"]/gm)]
      .map(x=>x[1]),
    ...[...source.matchAll(/^\s*import\s*['"]([^'"]+)['"]/gm)].map(x=>x[1])
  ];
  for(const specifier of specifiers){
    const dep=resolveRelative(path,specifier);
    if(dep)walk(dep);
  }
  // A script must not create a hidden old-origin database or use a plaintext
  // browser fallback anywhere in the validated runtime's dependency tree.
  if(/\bexamprep-v1\b/.test(source)&&!name.endsWith('encryptedExamRuntime.ts')){
    fail('legacy database identifier referenced in encrypted runtime dependency: '+name);
  }
}
walk(entry);
if(!visited.has('src/catalogValidation.ts')||
   !visited.has('src/backup.ts')||
   visited.has('src/db.ts')){
  fail('pure catalog/backup validation boundary not established');
}
console.log('Encrypted-only runtime dependency boundary PASS: '+
  visited.size+' statically imported source files; no legacy IndexedDB dependency.');
